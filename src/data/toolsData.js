// Get prompts that match a given tool
export function getPromptsForTool(tool, allPrompts) {
    if (!tool.companyKeys || tool.companyKeys.length === 0) return [];
    return allPrompts.filter(p =>
        tool.companyKeys.some(key =>
            p.company.toLowerCase().includes(key.toLowerCase()) ||
            p.tool.toLowerCase().includes(key.toLowerCase())
        )
    );
}

// Get tool by company name from prompts
export function getToolByCompany(company, tools) {
    return tools.find(t =>
        t.companyKeys.some(k => company.toLowerCase().includes(k.toLowerCase()))
    );
}

